"""
Check every game against the minimum number of questions per book, using content/question-list.csv.
Writes content/coverage-report.md (one table per game, with the books that fall short).

Minimums (proposed; agree them with the partner reviewers):
  Bible Trivia                 10 per book  (a quiz is 10 questions)
  Memory Verse                  3 per book
  Crossword and Word Search     1 word list of 10 words per book
  Echo                          1 passage per book
  Bible Characters              3 per book  (books without named people are listed separately)
  Story Builder                 1 story per book (narrative books; others are listed separately)
  Who Said It                   3 per book  (books whose text names speakers; others are listed separately)
  Scene Detective               exempt: scenes come from the Gospels, Acts and the Covenant film only

Run with --strict to exit with an error if a core game (Trivia, Memory, Crossword, Echo) is short.
Run without it to print the report and keep going (the default, used by the publishing workflow).
"""
import csv
import os
import sys
from collections import Counter, defaultdict

BOOKS = ["Genesis","Exodus","Leviticus","Numbers","Deuteronomy","Joshua","Judges","Ruth","1 Samuel","2 Samuel",
 "1 Kings","2 Kings","1 Chronicles","2 Chronicles","Ezra","Nehemiah","Esther","Job","Psalms","Proverbs",
 "Ecclesiastes","Song of Songs","Isaiah","Jeremiah","Lamentations","Ezekiel","Daniel","Hosea","Joel","Amos",
 "Obadiah","Jonah","Micah","Nahum","Habakkuk","Zephaniah","Haggai","Zechariah","Malachi",
 "Matthew","Mark","Luke","John","Acts","Romans","1 Corinthians","2 Corinthians","Galatians","Ephesians",
 "Philippians","Colossians","1 Thessalonians","2 Thessalonians","1 Timothy","2 Timothy","Titus","Philemon",
 "Hebrews","James","1 Peter","2 Peter","1 John","2 John","3 John","Jude","Revelation"]
assert len(BOOKS) == 66
# books whose text has no named individuals to build a Bible Characters round from (proposal)
NO_CHARACTERS = {"Leviticus","Deuteronomy","Psalms","Proverbs","Ecclesiastes","Song of Songs","Lamentations",
  "Obadiah","Joel","Amos","Micah","Nahum","Habakkuk","Zephaniah","Haggai","Zechariah","Malachi","Galatians",
  "1 Thessalonians","2 Thessalonians","1 Peter","2 Peter","1 John","2 John","3 John","Jude","Ephesians","Titus","Philemon"}
# books without a continuous narrative for a Story Builder card sequence (proposal)
NO_STORY = set(BOOKS) - {"Genesis","Exodus","Numbers","Joshua","Judges","Ruth","1 Samuel","2 Samuel","1 Kings",
  "2 Kings","1 Chronicles","2 Chronicles","Ezra","Nehemiah","Esther","Job","Daniel","Jonah","Matthew","Mark",
  "Luke","John","Acts"}
# books whose text names speakers in the way Who Said It needs (proposal; the generator found 22 so far)
# letters, poems, wisdom books and most prophecies do not name the speakers in a way Who Said It can use (proposal)
NO_SPEAKERS = {"Psalms","Proverbs","Ecclesiastes","Song of Songs","Lamentations","Ezekiel","Hosea","Joel","Obadiah",
  "Micah","Nahum","Habakkuk","Zephaniah","Haggai","Zechariah","Malachi","Romans","1 Corinthians","Ephesians",
  "Colossians","Philippians","1 Thessalonians","2 Thessalonians","1 Timothy","2 Timothy","Titus","Hebrews","James",
  "1 Peter","2 Peter","1 John","2 John","3 John","Jude","Revelation"}

rows = list(csv.DictReader(open(os.path.join("content", "question-list.csv"), encoding="utf-8")))
per = defaultdict(Counter)
for r in rows:
    per[r["Game"]][r["Book"]] += 1
# crossword and word search share one list per book: count word lists, not words
word_lists = Counter()
for r in rows:
    if r["Game"] == "Crossword and Word Search":
        word_lists[r["Book"]] += 1
word_lists = {b: n // 10 for b, n in word_lists.items()}

def table(title, need, count_of, exempt=set(), core=False):
    short = [b for b in BOOKS if b not in exempt and count_of(b) < need]
    met = len([b for b in BOOKS if b not in exempt]) - len(short)
    return {"title": title, "need": need, "met": met, "exempt": sorted(exempt), "short": short, "core": core}

checks = [
    table("Bible Trivia", 10, lambda b: per["Bible Trivia"][b], core=True),
    table("Memory Verse", 3, lambda b: per["Memory Verse"][b], core=True),
    table("Crossword and Word Search (one 10-word list)", 1, lambda b: word_lists.get(b, 0), core=True),
    table("Echo (one passage)", 1, lambda b: per["Echo"][b], core=True),
    table("Bible Characters (three per book)", 3, lambda b: per["Bible Characters"][b], exempt=NO_CHARACTERS),
    table("Story Builder (one story)", 1, lambda b: per["Story Builder"][b], exempt=NO_STORY),
    table("Who Said It (three per book)", 3, lambda b: per["Who Said It"][b], exempt=NO_SPEAKERS),
]

out = os.path.join("content", "coverage-report.md")
with open(out, "w", encoding="utf-8") as f:
    f.write("# Wordplay coverage report\n\nGenerated by `scripts/coverage_check.py` from `content/question-list.csv`.\n\n")
    f.write("| Game | Minimum | Books that meet it | Books short | Exempt (proposal) |\n|---|---|---:|---:|---:|\n")
    for c in checks:
        f.write(f"| {c['title']} | {c['need']} | {c['met']} | {len(c['short'])} | {len(c['exempt'])} |\n")
    f.write("\n## Books that fall short\n\n")
    for c in checks:
        f.write(f"### {c['title']}\n\n")
        f.write((", ".join(c["short"]) if c["short"] else "None. Every book meets the minimum.") + "\n\n")
        if c["exempt"]:
            f.write(f"Exempt (proposal, to agree): {', '.join(c['exempt'])}\n\n")
    f.write("Scene Detective is not counted: its scenes come only from the Gospels, Acts and the Covenant film.\n")

print(f"Wrote {out}")
for c in checks:
    print(f"  {c['title']:48} meets: {c['met']:>2}/{66 - len(c['exempt'])}   short: {len(c['short'])}")
core_short = [c for c in checks if c["core"] and c["short"]]
if "--strict" in sys.argv and core_short:
    print("Core games short: " + ", ".join(c["title"] for c in core_short))
    sys.exit(1)
